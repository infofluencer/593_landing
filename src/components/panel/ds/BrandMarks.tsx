export function BrandNavIcon({
  href,
  className = "size-[18px] shrink-0",
}: {
  href: string;
  className?: string;
}) {
  switch (href) {
    case "/meta":
      return <MetaMark className={className} />;
    case "/google":
      return <GoogleAdsMark className={className} />;
    case "/ga4":
      return <Ga4Mark className={className} />;
    case "/gtm":
      return <GtmMark className={className} />;
    case "/search-console":
      return <GscMark className={className} />;
    default:
      return null;
  }
}

export function isBrandNavHref(href: string): boolean {
  return (
    href === "/meta" ||
    href === "/google" ||
    href === "/ga4" ||
    href === "/gtm" ||
    href === "/search-console"
  );
}
